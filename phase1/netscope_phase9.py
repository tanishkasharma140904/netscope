lock = threading.Lock()


# =============================================================
#   FUNCTION: analyze_packet(packet)
# =============================================================
#
#   Called by Scapy for EVERY packet captured.
#
#   Responsibilities:
#
#       Phase 3 → Protocol Counters
#
#       Phase 4 → IP Tracking
#
#       Phase 5 → Port Tracking
#
#       Phase 6 → Bandwidth Tracking
#
#       Phase 7 → Supplies data used by
#                 anomaly detection
#
#       Phase 8 → Session Tracking
#
#       Phase 9 → Application Classification
#
# =============================================================

def analyze_packet(packet):

    if not packet.haslayer(IP):
        return

    ip_layer = packet[IP]

    src_ip = ip_layer.src
    dst_ip = ip_layer.dst

    packet_size = len(packet)

    with lock:

        # =====================================================
        # PROTOCOL COUNTERS
        # =====================================================

        counters["total"] += 1

        if packet.haslayer(TCP):

            counters["tcp"] += 1

        elif packet.haslayer(UDP):

            counters["udp"] += 1

        elif packet.haslayer(ICMP):

            counters["icmp"] += 1

        else:

            counters["other"] += 1

        # =====================================================
        # TOP TALKER ANALYSIS
        # =====================================================

        ip_tracker[src_ip] += 1
        ip_tracker[dst_ip] += 1

        # =====================================================
        # PORT ANALYSIS
        # =====================================================

        if packet.haslayer(TCP):

            tcp_layer = packet[TCP]

            port_tracker[tcp_layer.sport] += 1
            port_tracker[tcp_layer.dport] += 1

        elif packet.haslayer(UDP):

            udp_layer = packet[UDP]

            port_tracker[udp_layer.sport] += 1
            port_tracker[udp_layer.dport] += 1

        # =====================================================
        # BANDWIDTH TRACKING
        # =====================================================

        bandwidth["total_bytes"] += packet_size

        bandwidth["window_bytes"] += packet_size

        bandwidth["window_packets"] += 1

        # ======================================================
        # PHASE 8 — SESSION TRACKING
        # ======================================================

        protocol = "OTHER"
        src_port = 0
        dst_port = 0

        if packet.haslayer(TCP):

            protocol = "TCP"

            src_port = packet[TCP].sport
            dst_port = packet[TCP].dport

        elif packet.haslayer(UDP):

            protocol = "UDP"

            src_port = packet[UDP].sport
            dst_port = packet[UDP].dport

        elif packet.haslayer(ICMP):

            protocol = "ICMP"

        session_key = build_session_key(
            src_ip,
            dst_ip,
            protocol,
            src_port,
            dst_port
        )

        current_time = time.time()

        if session_key not in session_tracker:

            session_tracker[session_key] = {

                "packets": 0,
                "bytes": 0,

                "first_seen": current_time,
                "last_seen": current_time

            }

        session_tracker[session_key]["packets"] += 1

        session_tracker[session_key]["bytes"] += packet_size

        session_tracker[session_key]["last_seen"] = current_time

        # ======================================================
        # PHASE 9 — APPLICATION CLASSIFICATION
        # ======================================================
        #
        # For TCP/UDP packets: classify based on ports.
        # For ICMP/OTHER: no application classification
        #   (they have no ports).
        #
        # ======================================================

        if packet.haslayer(TCP) or packet.haslayer(UDP):

            app_name = classify_application(
                src_port,
                dst_port
            )

            app_tracker[app_name] += 1


# =============================================================
#   FUNCTION: format_bytes()
# =============================================================
#
#   Converts:
#
#       500
#
#   into:
#
#       500 B
#
#
#       2048
#
#   into:
#
#       2.00 KB
#
# =============================================================

def format_bytes(num_bytes):

    KB = 1024
    MB = 1024 ** 2
    GB = 1024 ** 3

    if num_bytes >= GB:

        return f"{num_bytes / GB:.2f} GB"

    elif num_bytes >= MB:

        return f"{num_bytes / MB:.2f} MB"

    elif num_bytes >= KB:

        return f"{num_bytes / KB:.2f} KB"

    else:

        return f"{int(num_bytes)} B"


# =============================================================
#   FUNCTION: make_bar()
# =============================================================
#
#   Creates proportional visual bars.
#
# =============================================================

def make_bar(count, max_count, bar_width=20):

    if max_count == 0:

        return " " * bar_width

    filled = int(
        (count / max_count) * bar_width
    )

    empty = bar_width - filled

    return (
        "█" * filled
        +
        "░" * empty
    )


# =============================================================
#   FUNCTION: add_alert()
# =============================================================
#
#   Adds alerts safely.
#
#   Keeps only newest MAX_ALERTS entries.
#
# =============================================================

def add_alert(message):

    timestamp = datetime.now().strftime(
        "%H:%M:%S"
    )

    entry = f"[{timestamp}] {message}"

    alerts.append(entry)

    if len(alerts) > MAX_ALERTS:

        alerts.pop(0)


# =============================================================
#   FUNCTION: detect_anomalies()
# =============================================================
#
#   Phase 7 Core Engine + Phase 9 Extension
#
# =============================================================
#
#   Detection Rules:
#
#   Rule 1
#       UDP > 70%
#
#   Rule 2
#       ICMP > 20%
#
#   Rule 3
#       Bandwidth > 500 KB/sec
#
#   Rule 4
#       Single Host > 80%
#
#   Rule 5 (Phase 9)
#       OTHER application traffic > 30%
#
# =============================================================

def detect_anomalies(

    total,
    udp,
    icmp,
    bytes_per_sec,
    top_ips,
    app_counts

):

    current_alerts = []

    # =========================================================
    # RULE 1
    # HIGH UDP TRAFFIC
    # =========================================================

    if total > 0:

        udp_pct = (
            udp / total
        ) * 100

        if udp_pct > UDP_THRESHOLD:

            message = (
                "HIGH UDP TRAFFIC DETECTED"
            )

            current_alerts.append(
                f"⚠ {message}"
            )

    # =========================================================
    # RULE 2
    # HIGH ICMP TRAFFIC
    # =========================================================

    if total > 0:

        icmp_pct = (
            icmp / total
        ) * 100

        if icmp_pct > ICMP_THRESHOLD:

            message = (
                "HIGH ICMP TRAFFIC DETECTED"
            )

            current_alerts.append(
                f"⚠ {message}"
            )

    # =========================================================
    # RULE 3
    # BANDWIDTH SPIKE
    # =========================================================

    if bytes_per_sec > BANDWIDTH_THRESHOLD:

        message = (
            "BANDWIDTH SPIKE DETECTED"
        )

        current_alerts.append(
            f"⚠ {message}"
        )

    # =========================================================
    # RULE 4
    # HOST DOMINANCE
    # =========================================================

    if top_ips and total > 0:

        top_ip_count = top_ips[0][1]

        host_pct = (
            top_ip_count / total
        ) * 100

        if host_pct > HOST_DOMINANCE_THRESHOLD:

            message = (
                "HOST DOMINANCE DETECTED"
            )

            current_alerts.append(
                f"⚠ {message}"
            )

    # =========================================================
    # RULE 5 (PHASE 9)
    # EXCESSIVE UNKNOWN TRAFFIC
    # =========================================================
    #
    # If OTHER application traffic exceeds 30%
    # of total classified application traffic.
    #
    # =========================================================

    total_app_packets = sum(app_counts.values())

    if total_app_packets > 0:

        other_count = app_counts.get("OTHER", 0)

        other_pct = (
            other_count / total_app_packets
        ) * 100

        if other_pct > UNKNOWN_APP_THRESHOLD:

            message = (
                "EXCESSIVE UNKNOWN TRAFFIC DETECTED"
            )

            current_alerts.append(
                f"⚠ {message}"
            )

    # =========================================================
    # STORE ALERT HISTORY
    # =========================================================

    for alert in current_alerts:

        add_alert(alert)

    return current_alerts


