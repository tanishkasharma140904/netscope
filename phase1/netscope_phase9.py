# =============================================================
#   HELPER FUNCTION — classify_application()
# =============================================================
#
# Determines the application name for a packet
# based on its source and destination ports.
#
# Priority:
#
#   1. Check destination port first
#   2. Then check source port
#   3. If neither matches → OTHER
#
# =============================================================

def classify_application(src_port, dst_port):

    if dst_port in APP_PORT_MAP:

        return APP_PORT_MAP[dst_port]

    if src_port in APP_PORT_MAP:

        return APP_PORT_MAP[src_port]

    return "OTHER"


# =============================================================
#   HELPER FUNCTION — build_session_key()
# =============================================================
#
# Builds a unique session identifier.
#
# Example:
#
# (
#   "192.168.1.60",
#   "184.86.112.42",
#   "TCP",
#   51584,
#   443
# )
#
# =============================================================

def build_session_key(
    src_ip,
    dst_ip,
    protocol,
    src_port,
    dst_port
):

    return (
        src_ip,
        dst_ip,
        protocol,
        src_port,
        dst_port
    )


# =============================================================
